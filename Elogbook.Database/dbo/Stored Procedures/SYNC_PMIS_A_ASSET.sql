
-- ==========================================================================================
-- Lấy dữ liệu từ database từ QLKT_INFO (PMIS) đưa vào Elogbook để chuẩn bị đồng bộ dữ liệu
-- ==========================================================================================
CREATE PROCEDURE [dbo].[SYNC_PMIS_A_ASSET]
	@Asset_Input A_ASSET_TABLE_TYPE READONLY,
	@Company_Input S_COMPANY_TABLE_TYPE READONLY,
	@Country_Input G_ERP_COUNTRY_TABLE_TYPE READONLY
AS
BEGIN
	SET NOCOUNT ON

	--Company
	INSERT INTO dbo.PMIS_S_COMPANY(COMPID, COMPDESC, ADDRESS, EMAIL, TEL, FAX, NOTE, COMPID_PARENT, ORGID, TYPEIDLIST, HOMEPAGE, USER_CREATE_ID, 
		USER_CREATE_DTIME, USER_MODIFY_ID, USER_MODIFY_DTIME, ACTIVE, ATTACH_FILE, MUCDICH_SD_TROXI, 
		IsDeleted, CreatedUserID, InsertedAt, LastUpdatedUserID, UpdatedAt, JobID, status, IsSync)
	SELECT COMPID, COMPDESC, ADDRESS, EMAIL, TEL, FAX, NOTE, COMPID_PARENT, ORGID, TYPEIDLIST, HOMEPAGE, USER_CREATE_ID, 
		USER_CREATE_DTIME, USER_MODIFY_ID, USER_MODIFY_DTIME, ACTIVE, NULL, MUCDICH_SD_TROXI,
		IsDeleted, NULL, InsertedAt, NULL, UpdatedAt, JobID, NULL, NULL
	FROM @Company_Input
	
	--Country
	INSERT INTO dbo.PMIS_G_ERP_COUNTRY(COUNTRY_CODE, COUNTRY_NAME, IsDeleted, CreatedUserID, InsertedAt, LastUpdatedUserID, UpdatedAt, jobId, status, IsSync)
	SELECT COUNTRY_CODE, COUNTRY_NAME, IsDeleted, NULL, InsertedAt, NULL, UpdatedAt, jobId, ID, NULL 
	FROM @Country_Input

	--Asset
	INSERT INTO dbo.PMIS_A_ASSET(ASSETID, ASSETID_PARENT, ASSETID_ORG, ASSETDESC, ASSETORD, SITEID, CATEGORYID, TYPEID, MANDEPTIDLIST, USESTATUS_LAST_ID, 
		USESTATUS_LAST_DTIME, SERIALNUM, P_MANUFACTURERID, P_VENDORID, P_INSTALLDATE, P_PRICE, P_PRICEUOM, P_PRICE_INC_ALL_CHILD, [PRIORITY], USER_CR_ID, 
		USER_CR_DTIME, USER_MDF_ID, USER_MDF_DTIME, USESTATUS_UPDATE_ID, ASSETIDSORT, CHILDCOUNT, COUNTRY_ID, ISFIX, P_OPERATIONDATE, NONE_ATTACH, NONE_MATERIAL, 
		NONE_METER_DYN, NONE_SAFE, P_MAN_YEAR, USER_DEL_DTIME, USER_DEL_ID, ISDEL, CHILD_METER_DYN, CHILD_MATERIAL,
		JobId, IsDeleted, InsertedAt, UpdatedAt)
	SELECT ASSETID, ASSETID_PARENT, ASSETID_ORG, ASSETDESC, ASSETORD, SITEID, CATEGORYID, TYPEID, MANDEPTIDLIST, USESTATUS_LAST_ID, 
		USESTATUS_LAST_DTIME, SERIALNUM, P_MANUFACTURERID, P_VENDORID, P_INSTALLDATE, P_PRICE, P_PRICEUOM, P_PRICE_INC_ALL_CHILD, [PRIORITY], USER_CR_ID, 
		USER_CR_DTIME, USER_MDF_ID, USER_MDF_DTIME, USESTATUS_UPDATE_ID, ASSETIDSORT, CHILDCOUNT, COUNTRY_ID, ISFIX, P_OPERATIONDATE, NONE_ATTACH, NONE_MATERIAL, 
		NONE_METER_DYN, NONE_SAFE, P_MAN_YEAR, USER_DEL_DTIME, USER_DEL_ID, ISDEL, CHILD_METER_DYN, CHILD_MATERIAL,
		JobId, IsDeleted, InsertedAt, UpdatedAt 
	FROM @Asset_Input
END